// `ketch.lock`: one machine's set of tools, pinned to exact releases.
//
// Not the lock in `state` — that one is a mutex over the install tree, held for the length of a command. This is a
// file the user commits next to their dotfiles. `ketch lock` writes it from what is installed, `ketch sync` makes
// another machine match, and `ketch lock --check` says whether the two have drifted apart.
//
// What is reproducible here, and what is not:
//
// - The tag is. Every machine resolving the same tag gets the same release, which is the whole point of writing one
//   down.
// - The asset and its hash are reproducible only on the same target. A lock written on Apple Silicon names an
//   `aarch64` tarball an x86_64 Linux machine cannot run, so `sync` re-selects the asset there and verifies against
//   the source's own checksum instead. Claiming the recorded hash still applied would be a reproducibility guarantee
//   that quietly is not one.
//
// A lockfile is a file somebody else may have written — that is what sharing a dotfiles repository means — so nothing
// in it is allowed to choose a filesystem path. `sync` asks for a source at a tag and lets the usual manifest
// resolution decide the install name, the binaries, and where they land. The lock pins which release, never where it
// goes.
