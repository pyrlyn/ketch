/** Bumped only when the on-disk shape changes incompatibly. */
const val LOCK_VERSION = 1u

/** The name looked for when `--file` is not given. */
const val LOCK_FILE = "ketch.lock"

private const val SHA256_HEX = 64

/** A whole lockfile. Unknown keys are refused: they would be settings this ketch silently does not honour. */
@OptIn(ExperimentalSerializationApi::class)
@Serializable
data class Lockfile(
    val version: UInt,
    /**
     * Sorted by name, so the file is stable and its diffs are readable. Omitted entirely when empty: `package = []` is
     * not what "nothing is installed" should look like in a file people read.
     */
    @SerialName("package") @EncodeDefault(EncodeDefault.Mode.NEVER) val packages: List<LockedPackage> = emptyList(),
) {
    /** Every check that has to pass before a single entry is acted on. */
    internal fun validate(path: Path) {
        val where = path.toString()
        if (version > LOCK_VERSION) {
            throw KetchError.Msg(
                "$where was written by a newer ketch (lock version $version); upgrade with `ketch self upgrade`",
            )
        }
        // One bad entry fails the file rather than being skipped: unlike the registry, where a partial answer beats
        // none, a lockfile that installed most of itself would not be a lock at all.
        val seen = HashSet<String>()
        for (pkg in packages) pkg.validate(where, seen)
    }

    /** The file as it will be written. */
    fun toToml(): String =
        "# $LOCK_FILE — generated by `ketch lock`. Do not edit it by hand:\n" +
            "# run `ketch lock` again instead. Commit it.\n" +
            "#\n" +
            "# `ketch sync` installs every package below at the tag named here.\n" +
            "# The asset and sha256 apply to `target`; on any other machine ketch\n" +
            "# picks the asset that fits and verifies it against the source.\n" +
            render(this, LOCK_FILE)

    /** Write it out, atomically, so an interrupted write cannot leave a half-parsed lockfile where a whole one used to be. */
    fun save(path: Path) = writePrivate(path, toToml().encodeToByteArray())

    /**
     * The entry for an installed package, matched on source rather than name. The source is the stable identity: a
     * package can be renamed upstream, or installed under an alias, and still be the same thing to update.
     */
    private fun find(pkg: InstalledPackage): LockedPackage? = packages.firstOrNull { it.source == pkg.source }

    internal fun has(pkg: InstalledPackage) = find(pkg) != null

    companion object {
        /** Capture what is installed right now. */
        fun fromState(state: State) = Lockfile(LOCK_VERSION, state.iter().map(LockedPackage::fromInstalled).sortedWith(compareBy(BYTE_ORDER) { it.name }))

        /**
         * Read and check a lockfile. A missing one is not an empty one: `sync` with nothing to sync from is a mistake
         * worth naming, not a no-op to report as success.
         */
        fun load(path: Path): Lockfile {
            val text =
                try {
                    readText(path)
                } catch (e: FsException) {
                    if (e.kind != FsException.Kind.NotFound) throw KetchError.fsKit(path, e)
                    throw KetchError.Msg(
                        "no lockfile at $path. Run `ketch lock` to write one, or pass --file to point at another.",
                        e,
                    )
                }
            return parseChecked(text, path)
        }

        /** What [load] does after reading the file. */
        internal fun parseChecked(
            text: String,
            path: Path,
        ): Lockfile = parse<Lockfile>(text, path.toString()).also { it.validate(path) }
    }
}

/** One package, pinned. */
@OptIn(ExperimentalSerializationApi::class)
@Serializable
data class LockedPackage(
    /** The name it was installed under. Used to find the same manifest again, never to build a path. */
    val name: String,
    /** `scheme:id`, e.g. `github:BurntSushi/ripgrep`. */
    val source: PackageRef,
    /** Human-readable version. [tag] is what actually gets resolved. */
    val version: String,
    val tag: String,
    /** The target this entry was captured on, as `<os>-<arch>`. */
    val target: String,
    val asset: String,
    val sha256: String,
    @EncodeDefault(EncodeDefault.Mode.NEVER) val pinned: Boolean = false,
    /**
     * Which of several binaries sharing the package's name was chosen, as a file name. Absent when there was nothing
     * to choose; `ketch sync` feeds it to the choice so a machine without state or a terminal makes the same one.
     */
    @EncodeDefault(EncodeDefault.Mode.NEVER) val bin: String? = null,
    /**
     * When the build was published, for a package on a floating tag (`nightly`): the tag can be republished, and on
     * another target, where [sha256] names a file it never downloads, this is what still tells the locked build from
     * a new one. Absent for every other package.
     */
    @EncodeDefault(EncodeDefault.Mode.NEVER) val published: String? = null,
) {
    /**
     * True when the recorded asset and hash describe a machine like this one. Only then is the hash something to hold
     * a download to: on a different target the asset is a different file, and a mismatch would be correct rather than
     * suspicious.
     */
    fun matchesTarget(target: String) = this.target == target

    /**
     * True when the installed package is the release this entry pinned. The tag is always compared. The hash is only
     * a pin on the target that recorded it: another machine has a different asset, and a mismatch there would be the
     * expected one rather than drift.
     */
    internal fun matchesInstalled(installed: InstalledPackage): Boolean =
        when {
            installed.tag != tag -> false

            matchesTarget(installed.target.toString()) -> installed.sha256.eqIgnoreAsciiCase(sha256)

            // A floating tag holds still only as long as its build does.
            else -> published == null || installed.publishedAt == null || installed.publishedAt == published
        }

    /** Check this entry; [seen] holds the names before it, lowercased, as they are compared. */
    internal fun validate(
        where: String,
        seen: MutableSet<String>,
    ) {
        val named = "$where: package `$name`"
        // A target that is not one ketch recognises silently turns the entry into a cross-target one: the recorded
        // asset and hash stop applying, and a hash that drifted under the tag reads as clean.
        val github = source.scheme == "github"
        // Checked in order, each only once the ones before it pass, so the first problem is the one reported.
        val problem =
            when {
                // A target that is not one ketch recognises silently turns the entry into a cross-target one: the
                // recorded asset and hash stop applying, and a hash that drifted under the tag reads as clean.
                runCatching { TargetSpec.parse(target) }.isFailure -> {
                    "$named names `$target` as its target, which ketch does not know. Expected `<os>-<arch>`, e.g. `macos-aarch64`."
                }

                name.rustTrim().isEmpty() -> {
                    "$where: a package has no name"
                }

                // The name is matched against installed packages and shown to the user. A name that would have to be
                // rewritten to be usable is a name that does not mean what it says.
                sanitizeComponent(name) != name -> {
                    "$named is not a usable package name"
                }

                !seen.add(name.asciiLowercase()) -> {
                    "$named is listed twice"
                }

                tag.rustTrim().isEmpty() -> {
                    "$named has no tag to resolve"
                }

                !github && source.id.rustTrim().isEmpty() -> {
                    "$named has no source id"
                }

                else -> {
                    null
                }
            }
        problem?.let { throw KetchError.Msg(it) }
        if (github) validateRepo("source", source.id)
        extrasProblem(named)?.let { throw KetchError.Msg(it) }
    }

    private fun extrasProblem(named: String): String? {
        val p = published
        val b = bin
        return when {
            !isSha256(sha256) -> {
                "$named has `$sha256` where a sha256 belongs"
            }

            // Only ever compared, but also printed in the error that names a moved tag, so it cannot carry anything
            // a terminal would act on.
            p != null && (p.rustTrim().isEmpty() || !p.all { it == ' ' || it in '!'..'~' }) -> {
                "$named has `${escapeDebug(p)}` where a publication time belongs"
            }

            // A binary's file name: one path component, as written. It is only ever matched against files the
            // release ships, but a value that would need rewriting to be a file name cannot name one.
            b != null && (b.rustTrim().isEmpty() || sanitizeComponent(b) != b) -> {
                "$named has `$b` where a binary's file name belongs"
            }

            else -> {
                null
            }
        }
    }

    companion object {
        internal fun fromInstalled(pkg: InstalledPackage) =
            LockedPackage(
                name = pkg.name,
                source = pkg.source,
                version = pkg.version.toString(),
                tag = pkg.tag,
                target = pkg.target.toString(),
                asset = pkg.assetName,
                sha256 = pkg.sha256,
                pinned = pkg.pinned,
                bin = pkg.binChoice,
                published = pkg.publishedAt,
            )
    }
}

/** What `sync` would do, and what `--check` reports. */
data class Plan(
    /** Not installed at all. */
    val missing: List<LockedPackage> = emptyList(),
    /** Installed, at a different tag. Carries the tag actually present. */
    val changed: List<Pair<LockedPackage, String>> = emptyList(),
    /** Installed, and the lockfile says nothing about it. */
    val extra: List<String> = emptyList(),
    /** Installed at exactly the locked tag. */
    val matched: Int = 0,
) {
    /**
     * True when the tree already is what the lockfile describes. `--prune` decides whether extras count against that,
     * because a lockfile is a record of what you want, not necessarily of all you have.
     */
    fun isClean(includingExtras: Boolean) = missing.isEmpty() && changed.isEmpty() && (!includingExtras || extra.isEmpty())
}

/** Compare a lockfile against what is installed. */
fun plan(
    lock: Lockfile,
    state: State,
): Plan {
    val installed = state.iter()
    val missing = mutableListOf<LockedPackage>()
    val changed = mutableListOf<Pair<LockedPackage, String>>()
    var matched = 0
    for (entry in lock.packages) {
        val found = installed.firstOrNull { it.source == entry.source }
        when {
            found == null -> missing += entry
            entry.matchesInstalled(found) -> matched++
            else -> changed += entry to found.tag
        }
    }
    val extra = installed.filterNot(lock::has).map { it.name }
    return Plan(missing, changed, extra, matched)
}

/** Where the lockfile lives: what was asked for, or `ketch.lock` here. */
fun path(explicit: Path?): Path = explicit ?: Path(LOCK_FILE)

private fun isSha256(text: String) = text.length == SHA256_HEX && text.all { it in '0'..'9' || it in 'a'..'f' || it in 'A'..'F' }
