/** How a lockfile is written and read back: schema, layout, snapshot, round trips. */
class LockfileFormatTest {
    @Test
    fun theCommittedLockSchemaDescribesEveryLockfileKey() {
        // Rust regenerates the schema from its types; the port checks its own types have not drifted from it.
        val schema = Json.parseToJsonElement(readText(joinPath(RUST_FIXTURES, "lock.schema.json"))).jsonObject

        fun keys(of: kotlinx.serialization.descriptors.SerialDescriptor) = (0 until of.elementsCount).map(of::getElementName).toSet()
        assertEquals(schema.getValue("properties").jsonObject.keys, keys(serializer<Lockfile>().descriptor))
        val locked =
            schema
                .getValue("\$defs")
                .jsonObject
                .getValue("LockedPackage")
                .jsonObject
        assertEquals(locked.getValue("properties").jsonObject.keys, keys(serializer<LockedPackage>().descriptor))
    }

    @Test
    fun aWrittenLockfileValidatesAgainstTheSchema() {
        val schema = Schema.file("lock.schema.json")
        val pkg = installed("fd", "sharkdp/fd", "v10.2.0").copy(binChoice = "fd", publishedAt = "2026-10-01T00:00:00Z", pinned = true)
        val text = lockOf(stateWith(pkg)).toToml()
        assertEquals(emptyList(), schema.errors(toJson(text, "test")))
    }

    @Test
    fun previousRetainedIsTheFirstKeptVersion() {
        val pkg = installed("rg", "BurntSushi/ripgrep", "v14.0.0")
        assertNull(pkg.previousRetained())
        val kept = pkg.copy(retained = listOf(RetainedVersion.fromInstalled(pkg)))
        assertEquals("v14.0.0", kept.previousRetained()?.tag)
    }

    @Test
    fun aLockfileRoundTripsThroughToml() {
        val state = stateWith(installed("ripgrep", "BurntSushi/ripgrep", "14.1.1"), installed("fd", "sharkdp/fd", "v10.2.0"))
        val parsed = parse<Lockfile>(lockOf(state).toToml(), "test")
        assertEquals(lockOf(state).packages, parsed.packages)
    }

    @Test
    fun aLockfileIsWrittenByteForByteAsDocumented() {
        // Pinned so that moving the render call between modules, or changing the TOML writer, cannot change a file
        // people commit.
        val pkg = installed("fd", "sharkdp/fd", "v10.2.0").copy(target = TargetSpec.parse("macos-aarch64"), binChoice = "fd")
        assertEquals(
            """
            # ketch.lock — generated by `ketch lock`. Do not edit it by hand:
            # run `ketch lock` again instead. Commit it.
            #
            # `ketch sync` installs every package below at the tag named here.
            # The asset and sha256 apply to `target`; on any other machine ketch
            # picks the asset that fits and verifies it against the source.
            version = 1

            [[package]]
            name = "fd"
            source = "github:sharkdp/fd"
            version = "10.2.0"
            tag = "v10.2.0"
            target = "macos-aarch64"
            asset = "fd.tar.gz"
            sha256 = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
            bin = "fd"

            """.trimIndent(),
            lockOf(stateWith(pkg)).toToml(),
        )
    }

    @Test
    fun aWrittenLockfileSaysItIsGeneratedOnItsFirstLine() {
        val first = lockOf(stateWith()).toToml().lineSequence().first()
        assertTrue("generated by `ketch lock`" in first, first)
        assertTrue("Do not edit" in first, first)
    }

    @Test
    fun packagesAreWrittenInAStableOrder() {
        val state =
            stateWith(
                installed("ripgrep", "BurntSushi/ripgrep", "14.1.1"),
                installed("fd", "sharkdp/fd", "v10.2.0"),
                installed("jq", "jqlang/jq", "jq-1.7"),
            )
        assertEquals(listOf("fd", "jq", "ripgrep"), lockOf(state).packages.map { it.name })
    }

    @Test
    fun thePinnedFlagSurvivesARoundTrip() {
        val pkg = installed("fd", "sharkdp/fd", "v10.2.0").copy(pinned = true)
        assertTrue(parse<Lockfile>(lockOf(stateWith(pkg)).toToml(), "test").packages[0].pinned)
    }

    @Test
    fun aChosenBinaryRoundTripsAndStaysOutOfEntriesWithoutOne() {
        val chosen = installed("rtok", "me/rtok", "v1.0.0").copy(binChoice = "rtok-cli")
        val state = stateWith(chosen, installed("fd", "sharkdp/fd", "v10.2.0"))
        val text = lockOf(state).toToml()
        assertEquals(1, Regex("bin = ").findAll(text).count(), text)
        val parsed = parseChecked(text)
        assertEquals(lockOf(state).packages, parsed.packages)
        assertEquals("rtok-cli", parsed.packages.first { it.name == "rtok" }.bin)
    }

    @Test
    fun aLockfileWrittenBeforeBinExistedStillLoads() {
        assertNull(parseChecked(entry()).packages[0].bin)
    }

    @Test
    fun aTwoPackageLockfileRendersTheReviewedSnapshot() {
        // The Rust insta snapshot, so both ports write the same file from the same entries.
        val snapshot = readText(joinPath(RUST_FIXTURES, "lockfile-two-packages.snap")).substringAfter("---\n").substringAfter("---\n")
        val lock =
            Lockfile(
                LOCK_VERSION,
                listOf(
                    LockedPackage("fd", PackageRef.github("sharkdp/fd"), "10.2.0", "v10.2.0", "macos-aarch64", "fd.tar.gz", "a".repeat(64)),
                    LockedPackage(
                        "ripgrep",
                        PackageRef.github("BurntSushi/ripgrep"),
                        "14.1.1",
                        "14.1.1",
                        "macos-aarch64",
                        "ripgrep.tar.gz",
                        "b".repeat(64),
                        pinned = true,
                    ),
                ),
            )
        // insta strips the trailing newline it stores; the file ends in one.
        assertEquals(snapshot.trimEnd('\n') + "\n", lock.toToml())
    }

    @Test
    fun aRenderedLockfileReadsBackWhatWasWritten() {
        // The proptest as a seeded sample: names compare case-insensitively at validation, so the first spelling wins
        // and the file holds each package once.
        val random = Random(SEED)
        val repos = listOf("BurntSushi/ripgrep", "sharkdp/fd", "jqlang/jq")
        val targets = listOf("macos-aarch64", "linux-x86_64", "windows-x86_64")
        repeat(SAMPLES) {
            val byName = LinkedHashMap<String, LockedPackage>()
            repeat(random.nextInt(4)) {
                val name = (1..random.nextInt(1, 9)).map { 'a' + random.nextInt(26) }.joinToString("")
                val (major, minor, patch) = List(3) { random.nextInt(50) }
                byName.getOrPut(name) {
                    LockedPackage(
                        name,
                        PackageRef.github(repos.random(random)),
                        "$major.$minor.$patch",
                        "v$major.$minor.$patch",
                        targets.random(random),
                        "tool.tar.gz",
                        (1..64).map { "0123456789abcdef"[random.nextInt(16)] }.joinToString(""),
                        pinned = random.nextBoolean(),
                    )
                }
            }
            val lock = Lockfile(LOCK_VERSION, byName.values.sortedBy { it.name })
            val parsed = parse<Lockfile>(lock.toToml(), "test")
            parsed.validate(Path("sample"))
            assertEquals(lock.packages, parsed.packages)
        }
    }

    private companion object {
        const val SEED = 20261027
        const val SAMPLES = 256
    }
}
